def _question_step(question, sphere_key=None):
    """Шаг по словам вопроса — или None, если ничего не подошло."""
    if not question:
        return None
    normalized = normalize(question)
    for words, step, themes in QUESTION_STEPS:
        if themes and sphere_key not in themes:
            continue
        for word in words:
            if normalize(word) in normalized:
                return step
    return None


