def parse_birth(text):
    """Разбирает дату рождения. Возвращает (date, time_str) или (None, None).

    Принимает: 15.03.1990, 15/03/1990, 15-03-1990, 1990-03-15,
    «15 марта 1990», опционально со временем: «15.03.1990 14:30».
    """
    text = (text or "").strip().lower()
    time_str = None
    m_time = re.search(r"(?<![\d.])([01]?\d|2[0-3])[:.]([0-5]\d)(?![\d.])", text)
    if m_time:
        time_str = "%02d:%s" % (int(m_time.group(1)), m_time.group(2))
        text = (text[:m_time.start()] + " " + text[m_time.end():]).strip()

    day = month = year = None

    m = re.search(r"\b(\d{4})[.\-/](\d{1,2})[.\-/](\d{1,2})\b", text)
    if m:
        year, month, day = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if day is None:
        m = re.search(r"\b(\d{1,2})[.\-/\s](\d{1,2})[.\-/\s](\d{4})\b", text)
        if m:
            day, month, year = int(m.group(1)), int(m.group(2)), int(m.group(3))
    if day is None:
        m = re.search(r"\b(\d{1,2})\s+([а-я]+)\s+(\d{4})\b", text)
        if m and m.group(2) in MONTHS_RU:
            day, month, year = int(m.group(1)), MONTHS_RU[m.group(2)], int(m.group(3))

    if day is None or not (1900 <= (year or 0) <= dt.date.today().year):
        return None, None
    try:
        birth = dt.date(year, month, day)
    except ValueError:
        return None, None
    if birth > dt.date.today():
        return None, None
    return birth, time_str


def _table_sun_sign(date):
    """Знак Солнца по усреднённой таблице границ — запасной вариант."""
    key = "capricorn"
    for (m, d), sign in _SIGN_BOUNDS:
        if (date.month, date.day) >= (m, d):
            key = sign
    return key


def sun_sign(date):
    """Знак Солнца на дату — по настоящему положению светила.

    Границы знаков плавают: Солнце входит в Овен то 20, то 21 марта, и
    усреднённая таблица на стыках ошибается. Проверка на ста годах дала
    47 расхождений на 1188 дат у границ — каждый раз это человек,
    родившийся на стыке и услышавший чужой знак.

    Считаем на полдень по всемирному времени: без времени рождения точнее
    не выйдет, и на несколько часов у самой границы знак всё ещё может
    разойтись — об этом бот предупреждает отдельно (см. on_cusp).
    """
    if natal.available():
        try:
            return forecast.positions_for(date)["sun"]["sign"]
        except Exception:
            log.warning("не удалось определить знак по эфемеридам",
                        exc_info=True)
    return _table_sun_sign(date)


def on_cusp(date):
    """True, если дата в пределах суток от границы знаков."""
    for delta in (-1, 1):
        if sun_sign(date + dt.timedelta(days=delta)) != sun_sign(date):
            return True
    return False


