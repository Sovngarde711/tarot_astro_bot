def _rng(parts):
    digest = hashlib.sha256("|".join(parts).encode("utf-8")).hexdigest()
    return random.Random(int(digest[:16], 16))


def draw_cards(positions, seed_parts):
    """Карты на заданные позиции. Один и тот же seed — один и тот же расклад."""
    rng = _rng(seed_parts)
    cards = rng.sample(td.ALL_CARDS, len(positions))
    return [
        {"position": pos, "card": card, "reversed": rng.random() < REVERSED_CHANCE}
        for pos, card in zip(positions, cards)
    ]


def client_seed(profile):
    return [(profile.get("name") or "").lower(), str(profile.get("birth") or "")]


def draw_spread(sphere_key, profile, on_date=None):
    """Тянет карты на позиции темы. Детерминированно для клиента и дня."""
    day = on_date or dt.date.today()
    return draw_cards(
        SPHERES[sphere_key]["positions"],
        [sphere_key] + client_seed(profile) + [day.isoformat()],
    )




