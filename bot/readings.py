MAX_WORDS_FOR_SPHERE = 4


def match_sphere(text):
    """Реплика вроде «про деньги» или «что он ко мне чувствует» -> ключ темы.

    Ограничение по длине нужно из-за коротких корней: «муж» встречается и
    в «Венера в 7 доме у мужчины», а это вопрос к справочнику, а не заявка
    на разбор про любовь. Поэтому короткие корни ищем только в короткой
    реплике.

    Многословные приметы («ко мне чувств», «своё дело») двусмысленными не
    бывают, и их ищем в тексте любой длины: самый частый вопрос про чужие
    чувства как раз длиннее четырёх слов.
    """
    normalized = normalize(text)
    if not normalized:
        return None
    short = len(normalized.split()) <= MAX_WORDS_FOR_SPHERE
    for key, words in SPHERE_WORDS.items():
        for word in words:
            needle = normalize(word)
            if needle in normalized and (short or " " in needle):
                return key
    return None

