def lower_first(text):
    return text[:1].lower() + text[1:] if text else text


def _short_summary(sphere, draw, seed=()):
    """«Коротко» — весь расклад обычным языком, по одной строке на позицию.

    Здесь и только здесь карты говорят человеческим языком; в блоке
    «Карты» те же номера получают классическое значение из колоды.
    Раньше понятная фраза стояла в обоих местах, и разбор выглядел так,
    будто бот повторяется.
    """
    positions = sphere["positions"]
    lines = []
    for number, item in enumerate(draw, 1):
        label = positions[number - 1] if number <= len(positions) else "Ещё"
        lines.append("<b>%d. %s.</b> %s."
                     % (number, label, as_sentence(plain_card(item))))
    return "\n".join(lines)


def dominant_suit(draw):
    """Масть, которой в раскладе больше всего (или «major», если старших)."""
    suits = {}
    for item in draw:
        suit = item["card"].get("suit") or "major"
        suits[suit] = suits.get(suit, 0) + 1
    top_suit, count = max(suits.items(), key=lambda kv: kv[1])
    return top_suit if count >= 2 else None


def _conclusion(sphere, draw, sphere_key, transit_line=None, timing=None,
                profile=None):
    """Вывод: ваш ход, чего не делать, когда и итог.

    Значения карт здесь не повторяются: они уже сказаны обычным языком в
    «Коротко» и классически — в «Карты». Этот блок добавляет то, чего
    выше не было: образ с карты совета, конкретный шаг руками, запрет
    через действие, даты и общий счёт расклада.
    """
    advice = draw[-1]
    blocks = []

    # «Ваш ход»: название блока не совпадает ни с одной позицией расклада
    # ни в одной теме — иначе заголовок встретился бы дважды
    action = ("Совет расклада — карта № %d, <b>%s</b>%s." % (
        len(draw), advice["card"]["name_ru"],
        " в перевёрнутом положении" if advice["reversed"] else ""))

    # Описание рисунка карты — готовый образ, написанный под каждый аркан.
    # Он делает совет зримым лучше любого нашего шаблона, и выше его нет.
    symbolism = advice["card"].get("symbolism")
    if symbolism:
        action += "\n<i>На карте: %s</i>" % after_colon(
            lower_first(_trim(symbolism, 220)))

    # Совет карты описывает состояние, а клиенту нужен шаг, который можно
    # сделать руками. Обычно его даёт пара «тема + преобладающая масть»,
    # но если человек сказал, что именно его волнует, отвечаем на это
    profile = profile or {}
    asked = _question_step(profile.get("question"), sphere_key)
    step = asked or ACTIONS.get(sphere_key, {}).get(dominant_suit(draw) or "major")
    if step:
        # точка, а не двоеточие: дальше идёт самостоятельное предложение
        # с заглавной, а после двоеточия в русском она неуместна
        action += "\n\n<b>Конкретно%s.</b> %s" % (
            " — по вашему вопросу" if asked else "", step)

    caveat = _chart_caveat(profile.get("chart"), sphere)
    if caveat:
        action += "\n%s" % caveat

    blocks.append("<b>Ваш ход</b>\n%s" % action)

    blocker = draw[1]
    avoid = ("Помеха — карта № 2, <b>%s</b>. %s"
             % (blocker["card"]["name_ru"], _avoid_step(sphere_key, blocker)))
    blocks.append("<b>Чего не делать</b>\n%s" % avoid)

    if timing:
        blocks.append("<b>Когда</b>\n%s" % timing)

    blocks.append(_final_block(sphere, draw, sphere_key, transit_line))
    return blocks


def _chart_caveat(chart, sphere):
    """Как делать шаг — с поправкой на карту этого человека.

    Берём только те факты, которые в разборе ещё не прозвучали советом:
    сам факт может быть назван в «Что в карте», но вывод из него — нет.
    Возвращаем не больше одного уточнения: два подряд превращают совет в
    оговорки.
    """
    if not chart:
        return None

    planet_key = sphere["planet"]
    position = chart["positions"].get(planet_key) or {}

    # Управитель темы: ретроградный — значит, возвращаться к начатому
    # выгоднее, чем начинать. В «Что в карте» про его ретроградность не
    # говорится, там названа только ретроградность планеты темы
    if chart.get("has_houses"):
        cusp_sign_key = natal.house_sign(chart, sphere["house"])
        if cusp_sign_key:
            ruler_key = ad.SIGNS[cusp_sign_key]["ruler"]
            ruler = chart["positions"].get(ruler_key) or {}
            if ruler.get("retro"):
                return ("Одно уточнение по вашей карте: %s, %s управляет "
                        "этой темой, идёт у вас ретроградно. На практике это "
                        "значит, что сейчас лучше идёт возвращённое и "
                        "доделанное, чем начатое с нуля: начните с того, что "
                        "уже было брошено на середине."
                        % (ad.PLANETS[ruler_key]["name_ru"],
                           plain.which(ruler_key)))

    house = position.get("house")
    if house == 12:
        return ("Одно уточнение по вашей карте: эта тема у вас живёт в "
                "закрытой части карты. Делайте шаг тихо, без объявлений и "
                "советов со стороны — при публичности она глохнет.")
    if house == 1:
        return ("Одно уточнение по вашей карте: эта тема завязана лично на "
                "вас. Делегировать и ждать, что кто-то сделает первый шаг, "
                "бесполезно — сдвинется только от вашего действия.")
    if position.get("retro"):
        return ("Одно уточнение по вашей карте: %s у вас идёт ретроградно, "
                "и эта сторона развёрнута внутрь. Сначала решите для себя и "
                "только потом объявляйте — в обратном порядке выходит хуже."
                % ad.PLANETS[planet_key]["name_ru"])
    return None


def _suit_explained(suit, count, total):
    """Почему мы вообще говорим про масть — одной фразой, без терминов.

    Без этой строки вывод звучит как приговор ниоткуда: клиент не знает,
    что масть карт в Таро отвечает за область жизни, и не понимает, из
    чего сделан вывод.
    """
    names = {
        "cups": "кубки, а это масть про чувства и отношения",
        "wands": "жезлы, а это масть про энергию, желание и действие",
        "swords": "мечи, а это масть про мысли, слова и решения",
        "pentacles": "пентакли, а это масть про деньги, работу и быт",
    }
    # «из четырёх карт две» — у числительных здесь разные падежи
    of_total = {2: "двух", 3: "трёх", 4: "четырёх", 5: "пяти"}
    plain_count = {1: "одна", 2: "две", 3: "три", 4: "четыре", 5: "пять"}
    return ("Видно это по мастям: из %s карт %s — %s."
            % (of_total.get(total, str(total)),
               plain_count.get(count, str(count)), names[suit]))


def _avoid_step(sphere_key, blocker):
    """Запрет, сформулированный действием, а не состоянием.

    «Чего не делать» без глагола превращается в диагноз: человек читает
    «затянувшаяся обида» и не понимает, что ему с этим делать сегодня.
    """
    weight = card_weight(blocker)
    if weight > 0:
        return ("Сама по себе она неплоха, но опираться сейчас только на "
                "неё не стоит: сильная сторона, которой пользуются слишком "
                "часто, со временем перестаёт выручать.")
    if weight == 0:
        return ("Не оставляйте её на самотёк: сама она не рассосётся, а "
                "будет тихо тормозить тему дальше.")
    return ("Не ищите ей оправданий и не ждите, что она уйдёт сама. Пока "
            "она держится, любой шаг вперёд даётся вдвое тяжелее.")


def _final_block(sphere, draw, sphere_key, transit_line=None):
    """«Итог»: из чего сделан вывод, к чему идёт дело и от чего это зависит.

    Сюда собрано всё, что говорит о раскладе как о целом: какая масть
    перевешивает, много ли старших арканов, каких карт больше — трудных
    или поддерживающих. По отдельности это были короткие блоки, которые
    повторяли друг друга разными словами.
    """
    suits = {}
    for item in draw:
        suit = item["card"].get("suit")
        if suit:
            suits[suit] = suits.get(suit, 0) + 1

    majors = sum(1 for item in draw if item["card"]["arcana"] == "major")
    if majors >= len(draw) / 2:
        # старших арканов больше половины — это не про быт, и сказать об
        # этом честнее, чем повторять название темы
        happening = ("Старших арканов в раскладе больше половины: тема вышла "
                     "за пределы бытового выбора. Решается не расписание на "
                     "неделю, а направление, в котором вы двинетесь дальше.")
    else:
        happening = ("Ничего судьбоносного расклад не показывает: тема «%s» "
                     "решается вашими обычными шагами." % sphere["title"].lower())

    if suits:
        top_suit, count = max(suits.items(), key=lambda kv: kv[1])
        if count >= 2:
            happening = {
                "cups": "Решают здесь чувства, а не расчёт: логика в этой "
                        "теме проигрывает тому, что вы на самом деле "
                        "чувствуете.",
                "wands": "Всё держится на вашей энергии и желании "
                         "действовать: захотите — сдвинется, остынете — "
                         "встанет.",
                "swords": "Всё упирается в слова и ясность в голове: пока "
                          "не названо вслух и не решено, ничего не "
                          "изменится.",
                "pentacles": "Всё упирается в деньги, быт и конкретные "
                             "дела — тема решается не разговорами, а "
                             "поступками, у которых есть цена.",
            }[top_suit]
            happening += " " + _suit_explained(top_suit, count, len(draw))
    if transit_line:
        happening += " " + transit_line

    supportive = sum(1 for item in draw if card_weight(item) > 0)
    difficult = sum(1 for item in draw if card_weight(item) < 0)

    lines = ["<b>Итог</b>", happening]

    if supportive > difficult:
        lines.append("Поддерживающих карт в раскладе больше, чем трудных, — "
                     "обстоятельства в целом на вашей стороне, и главный "
                     "риск здесь только один: ничего не делать.")
    elif difficult > supportive:
        lines.append("Трудных карт больше, чем поддерживающих. Это не "
                     "приговор, а честное предупреждение: быстро и легко "
                     "сейчас не выйдет, зато выйдет, если делать по шагу.")
    else:
        lines.append("Трудных и поддерживающих карт поровну: тема качается "
                     "и может пойти в любую сторону — перевесит то, куда вы "
                     "приложите силы.")

    lines.append(_closing_line(draw, sphere_key))
    return "\n".join(lines)


def _closing_line(draw, sphere_key):
    """Фраза, которой разбор заканчивается по смыслу, а не обрывается.

    Тон берётся из расклада: у застрявшей темы и у открытой дороги
    напутствие не может быть одинаковым.
    """
    total = len(draw)
    reversed_n = sum(1 for item in draw if item["reversed"])
    seed = [sphere_key, str(reversed_n), draw[0]["card"]["id"]]

    if reversed_n == 0:
        options = [
            "Такие расклады выпадают нечасто: дорога открыта, и единственное, "
            "что может её закрыть, — ваше промедление.",
            "Сопротивления нет ни изнутри, ни снаружи. Остаётся самое трудное — "
            "начать.",
        ]
    elif reversed_n >= total - 1:
        options = [
            "Не торопитесь. Тема сейчас требует не усилия, а терпения: сначала "
            "разобрать старое, и только потом строить.",
            "Это не тупик, а пауза. Она закончится, когда вы перестанете "
            "толкать закрытую дверь и оглядитесь.",
        ]
    else:
        options = [
            "Ничего непоправимого расклад не показывает — показывает работу, "
            "которую придётся сделать вам, а не обстоятельствам.",
            "Всё решаемо, но само не решится: карты описывают расстановку сил, "
            "а ход — за вами.",
        ]
    return "<i>%s</i>" % pick(options, seed)


