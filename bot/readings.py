# Оговорка про перевёрнутую карту. Вариантов несколько, потому что в
# «Коротко» таких карт может оказаться две подряд, и одна и та же фраза
# дважды в соседних предложениях режет слух.
REVERSED_MARKERS = [
    ", но с обратным знаком",
    ", и всё это с изнанки",
    ", только наоборот",
]


def keywords(item, count=2, variant=0):
    """Ключевые слова карты именной группой: «новая возможность и опора».

    В данных ключи описаны для прямого положения, поэтому у перевёрнутой
    карты их нельзя подавать как есть — смысл вывернется наизнанку. Прежняя
    пометка «(наоборот)» решала это, но выглядела технической сноской, а не
    речью, поэтому оговорка теперь встроена во фразу.
    """
    words = plain.join([word.lower() for word in item["card"]["keywords"][:count]])
    if not item["reversed"]:
        return words
    return words + REVERSED_MARKERS[variant % len(REVERSED_MARKERS)]


def as_sentence(text):
    """Первая буква заглавная — фраза становится самостоятельной."""
    text = (text or "").strip()
    return text[:1].upper() + text[1:]


def after_colon(text):
    """Фраза, которая встаёт после двоеточия.

    В понятных формулировках карт двоеточие встречается часто («появляется
    реальная возможность: деньги, работа или прочная основа»). Если такую
    фразу подставить в рамку, которая сама кончается двоеточием, в одном
    предложении окажется два — читать невозможно. Внутреннее двоеточие
    заменяем на тире: смысл тот же, знаки не сталкиваются.
    """
    return (text or "").replace(":", " —", 1)


def plain_card(item):
    """Карта одной понятной фразой — так, как сказал бы живой консультант.

    Классическое значение из data/ точное, но написано языком таролога.
    Человеку, который открыл бота впервые, нужна фраза про него самого,
    поэтому она лежит отдельно, в data/tarot_plain.py.
    """
    text = tp.plain(item["card"]["id"], item["reversed"])
    if text:
        return text
    # карты нет в таблице — не молчим, отдаём ключевые слова
    return keywords(item)


def card_weight(item):
    """Насколько карта благоприятна: +1 поддерживает, 0 ровно, −1 трудная."""
    return tp.weight(item["card"]["id"], item["reversed"])


def card_title(item):
    """«Башня» или «Башня в перевёрнутом положении».

    Форма нарочно бесполая: названия карт в русской колоде и мужского
    рода (Повешенный, Маг, Мир), и женского (Тройка, Башня, Звезда), а
    «выпавшая перевёрнутой» согласуется только с половиной из них.
    """
    return "%s%s" % (item["card"]["name_ru"],
                     " в перевёрнутом положении" if item["reversed"] else "")


def _meaning(item, limit=170):
    card = item["card"]
    return _trim(card["reversed"] if item["reversed"] else card["upright"], limit)


