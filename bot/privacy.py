        "«О персональных данных» и описывает то, что бот делает на самом "
        "деле.\n\n"

        "<b>1. Оператор.</b> %s. Связь по любым вопросам о данных — %s.\n\n"

        "<b>2. Какие данные собираются.</b> Только то, что вы сами "
        "вводите в диалоге:\n"
        "• имя или обращение — как к вам обращаться;\n"
        "• дата, время и место рождения — без них нельзя рассчитать "
        "натальную карту;\n"
        "• номер вашего чата в Telegram — его присваивает Telegram, по "
