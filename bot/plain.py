def join(items, union="и"):
    """«а, б и в» — перечисление с союзом, а не вереница запятых."""
    items = [item for item in items if item]
    if len(items) <= 1:
        return "".join(items)
    return "%s %s %s" % (", ".join(items[:-1]), union, items[-1])


