def gender(planet_key):
    if planet_key in FEMININE:
        return "f"
    if planet_key in NEUTER:
        return "n"
    return "m"


PRONOUN = {"m": "он", "f": "она", "n": "оно"}

# «Венера, которая управляет темой» — при подстановке названия планеты в
# придаточное нужен род: Сатурн который, Венера которая, Солнце которое
WHICH = {"m": "который", "f": "которая", "n": "которое"}


def which(planet_key):
    """«который» / «которая» / «которое» — по роду названия планеты."""
    return WHICH[gender(planet_key)]


def pronoun(planet_key):
    """«он» / «она» / «оно» — Сатурн мужского рода, Венера женского."""
    return PRONOUN[gender(planet_key)]


def possessive(planet_key, case="nominative"):
    """«ваш» / «ваша» / «ваше» в нужном падеже — по роду названия планеты."""
    return POSSESSIVE[case][gender(planet_key)]
