def plain(card_id, reversed_=False):
    """Понятная фраза о карте. Пустая строка, если карты нет в таблице."""
    record = PLAIN.get(card_id)
    if not record:
        return ""
    return record[3] if reversed_ else record[1]


def weight(card_id, reversed_=False):
    """Насколько карта благоприятна: +1, 0 или −1. Неизвестная — ноль."""
    record = PLAIN.get(card_id)
    if not record:
        return 0
    return record[2] if reversed_ else record[0]
